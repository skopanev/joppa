-- Байты вложений лежат ОТДЕЛЬНО от журнала, и это не оптимизация.
--
-- Проекция воркспейса строится перечитыванием всех событий подряд. Файл,
-- положенный в событие, читался бы при каждом таком перестроении — на
-- каждый запрос, вечно, ради метаданных, которые занимают сто байт.
-- Поэтому в журнал едет отпечаток, а содержимое — сюда.
--
-- Ключ — sha256 содержимого: один и тот же файл, приложенный к десяти
-- объектам, хранится один раз, и повторная загрузка ничего не добавляет.
CREATE TABLE IF NOT EXISTS joppa.blobs (
    hash text PRIMARY KEY CHECK (hash ~ '^[0-9a-f]{64}$'),
    bytes bytea NOT NULL,
    size bigint NOT NULL CHECK (size > 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
