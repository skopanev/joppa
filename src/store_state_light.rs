//! Part of `store_state`: the copy of a workspace for its meta row.
use super::*;

/// A copy of `w` without its large sections: objects, requirements, notes, criterion
/// boundaries, former test titles, document overrides and archived objects.
/// `changed_entries` compares them key by key.
/// The copy keeps every other field: the pattern names each field, so a new field of
/// Workspace fails to compile here until the copy takes it.
pub(super) fn light(w: &Workspace) -> Workspace {
    let Workspace {
        persistent_claims,
        replaying,
        in_place,
        claim_time_ms,
        alias,
        replay_epochs,
        claims_migrated,
        unloaded_objects,
        notes_migrated,
        object_aliases,
        objects: _,
        redactions,
        task_process,
        planning_claims,
        task_context,
        tasks_migrated,
        schema_migrated,
        consumers_migrated,
        consumer_drops_noted,
        test_rules_migrated,
        note_parents_migrated,
        body_migrated,
        purpose_migrated,
        test_nodes_migrated,
        generic_nodes,
        decision_required_migrated,
        prefix_from_title,
        documents_migrated,
        document_overrides: _,
        archived_objects: _,
        tree_schema,
        workspace_id,
        title,
        reference_prefix,
        admin,
        members,
        priorities,
        hidden_by,
        deleted_at,
        domains,
        tree_order,
        capabilities,
        consumers,
        projects,
        requirements: _,
        intake,
        questions,
        notes: _,
        ac_tests,
        criterion_boundaries: _,
        former_test_titles: _,
        remote_links,
    } = w;
    Workspace {
        persistent_claims: *persistent_claims,
        replaying: *replaying,
        in_place: *in_place,
        claim_time_ms: *claim_time_ms,
        alias: alias.clone(),
        replay_epochs: replay_epochs.clone(),
        claims_migrated: *claims_migrated,
        unloaded_objects: unloaded_objects.clone(),
        notes_migrated: *notes_migrated,
        object_aliases: object_aliases.clone(),
        objects: Default::default(),
        redactions: redactions.clone(),
        task_process: task_process.clone(),
        planning_claims: planning_claims.clone(),
        task_context: task_context.clone(),
        tasks_migrated: *tasks_migrated,
        schema_migrated: *schema_migrated,
        consumers_migrated: *consumers_migrated,
        consumer_drops_noted: *consumer_drops_noted,
        test_rules_migrated: *test_rules_migrated,
        note_parents_migrated: *note_parents_migrated,
        body_migrated: *body_migrated,
        purpose_migrated: *purpose_migrated,
        test_nodes_migrated: *test_nodes_migrated,
        generic_nodes: *generic_nodes,
        decision_required_migrated: *decision_required_migrated,
        prefix_from_title: *prefix_from_title,
        documents_migrated: *documents_migrated,
        document_overrides: Default::default(),
        archived_objects: Default::default(),
        tree_schema: tree_schema.clone(),
        workspace_id: workspace_id.clone(),
        title: title.clone(),
        reference_prefix: reference_prefix.clone(),
        admin: admin.clone(),
        members: members.clone(),
        priorities: priorities.clone(),
        hidden_by: hidden_by.clone(),
        deleted_at: *deleted_at,
        domains: domains.clone(),
        tree_order: tree_order.clone(),
        capabilities: capabilities.clone(),
        consumers: consumers.clone(),
        projects: projects.clone(),
        requirements: Default::default(),
        intake: intake.clone(),
        questions: questions.clone(),
        notes: Default::default(),
        ac_tests: ac_tests.clone(),
        criterion_boundaries: Default::default(),
        former_test_titles: Default::default(),
        remote_links: remote_links.clone(),
    }
}
